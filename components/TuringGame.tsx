import React, { useState } from 'react';
import { TuringRound, GameState } from '../types';
import { Scan, Fingerprint, Cpu, ArrowRight, RefreshCw, Check, X } from 'lucide-react';

const rounds: TuringRound[] = [
  {
    id: 1,
    imageA: "https://picsum.photos/seed/human1/500/500", 
    imageB: "https://picsum.photos/seed/ai1/500/500?blur=1", 
    correctAnswer: 'A',
    humanDescription: "Created by Kandinsky. Notice the varying pressure of the brushstrokes—some thick, some dry. This physical texture creates a depth that digital replications often smooth out or render too uniformly.",
    aiDescription: "Generated by Midjourney. While the composition is complex, the background textures lack organic randomness. The color blending is mathematically smooth, devoid of the 'muddy' mixing found in real paint."
  },
  {
    id: 2,
    imageA: "https://picsum.photos/seed/ai2/500/500?grayscale", 
    imageB: "https://picsum.photos/seed/human2/500/500?grayscale", 
    correctAnswer: 'B',
    humanDescription: "Charcoal sketch by a street artist. The smudge marks are inconsistent, reflecting the movement of a hand. There are faint eraser marks and paper texture that align with the medium's physical constraints.",
    aiDescription: "Stable Diffusion output. Notice the odd symmetry in the background shading—it repeats a pattern perfectly. Also, the hatching lines (shading lines) don't follow the 3D form of the object logically."
  },
  {
    id: 3,
    imageA: "https://picsum.photos/seed/human3/500/500",
    imageB: "https://picsum.photos/seed/ai3/500/500",
    correctAnswer: 'A',
    humanDescription: "Oil on canvas, 1920. The light source is consistent. The reflection in the water accurately distorts the object above it based on the angle. This physics-based consistency is intuitive to humans but hard for AI.",
    aiDescription: "DALL-E 3. Look closely at the reflection—it contains details that aren't in the object above it. Also, the 'brushstrokes' don't follow the form; they are just a surface filter. The lighting on the left object contradicts the shadow direction."
  }
];

const TuringGame: React.FC = () => {
  const [gameState, setGameState] = useState<GameState>({
    currentRoundIndex: 0,
    score: 0,
    isGameOver: false,
    history: []
  });
  const [roundResult, setRoundResult] = useState<'correct' | 'wrong' | null>(null);

  const currentRound = rounds[gameState.currentRoundIndex];

  const handleGuess = (guess: 'A' | 'B') => {
    if (roundResult !== null) return;

    const isCorrect = guess === currentRound.correctAnswer;
    setRoundResult(isCorrect ? 'correct' : 'wrong');
    
    // Update score immediately but don't advance yet
    setGameState(prev => ({
        ...prev,
        score: isCorrect ? prev.score + 1 : prev.score,
        history: [...prev.history, isCorrect]
    }));
  };

  const nextRound = () => {
    setRoundResult(null);
    if (gameState.currentRoundIndex < rounds.length - 1) {
        setGameState(prev => ({
            ...prev,
            currentRoundIndex: prev.currentRoundIndex + 1,
        }));
    } else {
        setGameState(prev => ({
            ...prev,
            isGameOver: true,
        }));
    }
  };

  const resetGame = () => {
    setGameState({
      currentRoundIndex: 0,
      score: 0,
      isGameOver: false,
      history: []
    });
    setRoundResult(null);
  };

  return (
    <section className="py-24 bg-[#111] text-white relative overflow-hidden">
      {/* Grid Background */}
      <div className="absolute inset-0 z-0 opacity-10" 
           style={{ backgroundImage: 'linear-gradient(#333 1px, transparent 1px), linear-gradient(90deg, #333 1px, transparent 1px)', backgroundSize: '40px 40px' }}>
      </div>

      <div className="max-w-6xl mx-auto px-4 relative z-10">
        
        {/* Header */}
        <div className="flex flex-col md:flex-row justify-between items-end mb-12 border-b border-gray-800 pb-6">
            <div>
                <h2 className="text-4xl md:text-5xl font-black tracking-tighter mb-2 flex items-center gap-3">
                    <Scan className="text-blue-500" size={40} />
                    TURING <span className="text-transparent bg-clip-text bg-gradient-to-r from-blue-500 to-white">FORENSICS</span>
                </h2>
                <p className="text-gray-400 font-mono text-sm uppercase tracking-widest">
                    Identify the human agency // Reject the synthetic
                </p>
            </div>
            <div className="flex items-center gap-4 mt-4 md:mt-0 font-mono">
                <div className="px-4 py-2 bg-gray-900 border border-gray-700 rounded text-sm">
                    ROUND: 0{gameState.currentRoundIndex + 1} / 0{rounds.length}
                </div>
                <div className="px-4 py-2 bg-gray-900 border border-gray-700 rounded text-sm text-blue-400">
                    SCORE: {gameState.score}
                </div>
            </div>
        </div>

        {!gameState.isGameOver ? (
          <div className="flex flex-col gap-8">
            {/* The Image Comparision Stage */}
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4 md:gap-12 relative">
                
                {/* VS Badge */}
                <div className="absolute top-1/2 left-1/2 transform -translate-x-1/2 -translate-y-1/2 z-20 bg-black border border-white/20 rounded-full p-2">
                    <span className="font-black italic text-xl">VS</span>
                </div>

                {/* Option A */}
                <ImageCard 
                    id="A"
                    src={currentRound.imageA}
                    isRevealed={roundResult !== null}
                    isHuman={currentRound.correctAnswer === 'A'}
                    onClick={() => handleGuess('A')}
                    isSelected={false} // Logic simplified for visual clarity
                    disabled={roundResult !== null}
                />

                {/* Option B */}
                <ImageCard 
                    id="B"
                    src={currentRound.imageB}
                    isRevealed={roundResult !== null}
                    isHuman={currentRound.correctAnswer === 'B'}
                    onClick={() => handleGuess('B')}
                    isSelected={false}
                    disabled={roundResult !== null}
                />
            </div>

            {/* Analysis / Result Panel */}
            <div className={`transition-all duration-500 ease-in-out overflow-hidden ${roundResult ? 'max-h-[600px] opacity-100' : 'max-h-0 opacity-0'}`}>
                <div className="bg-gray-900 border border-gray-700 rounded-xl p-8 shadow-2xl">
                    <div className="flex flex-col md:flex-row gap-8 items-start">
                        
                        {/* Status Indicator */}
                        <div className="md:w-1/4 flex flex-col items-center text-center border-b md:border-b-0 md:border-r border-gray-700 pb-6 md:pb-0 md:pr-6">
                            {roundResult === 'correct' ? (
                                <>
                                    <div className="w-16 h-16 rounded-full bg-green-500/20 flex items-center justify-center text-green-500 mb-4 animate-bounce">
                                        <Check size={32} strokeWidth={4} />
                                    </div>
                                    <h3 className="text-xl font-bold text-green-400 mb-1">IDENTIFIED</h3>
                                    <p className="text-sm text-gray-400">Human Agency Detected</p>
                                </>
                            ) : (
                                <>
                                    <div className="w-16 h-16 rounded-full bg-red-500/20 flex items-center justify-center text-red-500 mb-4 animate-pulse">
                                        <X size={32} strokeWidth={4} />
                                    </div>
                                    <h3 className="text-xl font-bold text-red-500 mb-1">DECEIVED</h3>
                                    <p className="text-sm text-gray-400">Synthetic mimicry successful</p>
                                </>
                            )}
                        </div>

                        {/* Text Analysis */}
                        <div className="md:w-3/4 flex flex-col gap-6">
                             <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
                                <div className="bg-black/40 p-4 rounded border-l-4 border-blue-500">
                                    <h4 className="flex items-center gap-2 font-bold text-blue-400 mb-2 text-sm uppercase">
                                        <Fingerprint size={16} /> Human Attributes
                                    </h4>
                                    <p className="text-gray-300 text-sm leading-relaxed">
                                        {currentRound.humanDescription}
                                    </p>
                                </div>
                                <div className="bg-black/40 p-4 rounded border-l-4 border-purple-500">
                                    <h4 className="flex items-center gap-2 font-bold text-purple-400 mb-2 text-sm uppercase">
                                        <Cpu size={16} /> Synthetic Artifacts
                                    </h4>
                                    <p className="text-gray-300 text-sm leading-relaxed">
                                        {currentRound.aiDescription}
                                    </p>
                                </div>
                             </div>

                             <button 
                                onClick={nextRound}
                                className="self-end flex items-center gap-2 bg-white text-black px-6 py-3 rounded hover:bg-gray-200 transition-colors font-bold tracking-wide"
                             >
                                NEXT ANALYSIS <ArrowRight size={18} />
                             </button>
                        </div>
                    </div>
                </div>
            </div>

          </div>
        ) : (
          <div className="bg-gray-900 border border-gray-800 p-12 rounded-3xl max-w-2xl mx-auto text-center relative overflow-hidden">
             <div className="absolute top-0 left-0 w-full h-1 bg-gradient-to-r from-blue-500 via-purple-500 to-blue-500"></div>
            <h3 className="text-5xl font-black mb-2 text-white">
                ANALYSIS COMPLETE
            </h3>
            <div className="text-8xl font-black text-transparent bg-clip-text bg-gradient-to-b from-white to-gray-600 my-8">
                {Math.round((gameState.score / rounds.length) * 100)}%
            </div>
            <p className="text-gray-400 mb-8 text-xl font-serif italic">
                {gameState.score === rounds.length 
                    ? "\"You possess the rare ability to see the soul in the stroke.\"" 
                    : "\"The line between creator and code is blurring before your eyes.\""}
            </p>
            <button 
                onClick={resetGame}
                className="inline-flex items-center px-8 py-4 bg-blue-600 hover:bg-blue-700 text-white font-bold rounded transition-colors uppercase tracking-widest text-sm"
            >
                <RefreshCw className="mr-2" size={18} /> Restart Sequence
            </button>
          </div>
        )}
      </div>
    </section>
  );
};

// Sub-component for the Image Card to handle complexity
const ImageCard: React.FC<{
    id: string;
    src: string;
    isRevealed: boolean;
    isHuman: boolean;
    onClick: () => void;
    disabled: boolean;
    isSelected: boolean;
}> = ({ id, src, isRevealed, isHuman, onClick, disabled }) => {
    
    return (
        <div 
            onClick={!disabled ? onClick : undefined}
            className={`
                relative group rounded-xl overflow-hidden cursor-pointer transition-all duration-500 border-2
                ${isRevealed 
                    ? (isHuman ? 'border-green-500 shadow-[0_0_30px_rgba(34,197,94,0.3)]' : 'border-red-500 opacity-60 grayscale') 
                    : 'border-gray-800 hover:border-blue-500 hover:shadow-2xl'
                }
            `}
        >
            {/* Image Layer */}
            <div className="relative aspect-square overflow-hidden bg-gray-900">
                <img 
                    src={src} 
                    alt={`Option ${id}`} 
                    className={`
                        w-full h-full object-cover transition-transform duration-700
                        ${!isRevealed && 'group-hover:scale-105'}
                        ${isRevealed && !isHuman ? 'animate-[glitch_0.3s_infinite]' : ''}
                    `} 
                />
                
                {/* Scanner Overlay (Active only when not revealed) */}
                {!isRevealed && (
                    <div className="absolute inset-0 opacity-0 group-hover:opacity-100 transition-opacity duration-300 pointer-events-none">
                        <div className="absolute top-0 left-0 w-full h-[2px] bg-blue-500 shadow-[0_0_10px_#3b82f6] animate-[scan_2s_linear_infinite]"></div>
                        <div className="absolute inset-0 bg-blue-500/10"></div>
                        <div className="absolute bottom-4 left-4 text-xs font-mono text-blue-400 bg-black/80 px-2 py-1">
                            SCANNING...
                        </div>
                    </div>
                )}

                {/* Result Overlay */}
                {isRevealed && (
                    <div className="absolute inset-0 flex items-center justify-center bg-black/40 backdrop-blur-[2px]">
                        <div className={`
                            px-6 py-3 border-2 font-black text-xl tracking-widest transform -rotate-12
                            ${isHuman 
                                ? 'border-green-500 text-green-500 bg-black/80' 
                                : 'border-red-500 text-red-500 bg-black/80 line-through decoration-2'
                            }
                        `}>
                            {isHuman ? 'AUTHENTIC' : 'SYNTHETIC'}
                        </div>
                    </div>
                )}
            </div>

            {/* Label */}
            <div className={`
                absolute top-4 left-4 font-black text-xl w-10 h-10 flex items-center justify-center rounded
                ${isRevealed 
                    ? (isHuman ? 'bg-green-500 text-black' : 'bg-red-500 text-white') 
                    : 'bg-white text-black'
                }
            `}>
                {id}
            </div>
            
            {/* Fake Data Corner */}
            <div className="absolute bottom-2 right-2 flex gap-1">
                 <div className="w-1 h-1 bg-white/50 rounded-full"></div>
                 <div className="w-1 h-1 bg-white/50 rounded-full"></div>
                 <div className="w-1 h-1 bg-white/50 rounded-full"></div>
            </div>
        </div>
    );
}

export default TuringGame;

